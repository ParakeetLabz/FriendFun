-- 🏆 Ultimate 2UI — leaderboard + daily win reward. Run once in the Supabase SQL Editor.
CREATE TABLE IF NOT EXISTS two_ui_scores (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id text NOT NULL,
  username text NOT NULL,
  score integer NOT NULL DEFAULT 0,
  created bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS two_ui_scores_game_idx ON two_ui_scores (game_id, score DESC);
CREATE TABLE IF NOT EXISTS two_ui_rewards (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id text NOT NULL,
  username text NOT NULL,
  day text NOT NULL,
  created bigint NOT NULL,
  UNIQUE (game_id, username, day)
);
