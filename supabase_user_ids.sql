-- 🆔 Numeric user IDs (profiles at #/users/1, #/users/2, ...)
-- Run this once in the Supabase SQL Editor.
-- Gives every user a short number: existing users get 1, 2, 3... in the
-- order they signed up, and new users get the next number automatically.
ALTER TABLE users ADD COLUMN IF NOT EXISTS user_id bigint GENERATED BY DEFAULT AS IDENTITY;
CREATE UNIQUE INDEX IF NOT EXISTS users_user_id_key ON users (user_id);
